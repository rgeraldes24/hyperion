struct DecodedVector
{
	std::string name;
	bytes message;
	bytes extendedPublicKey;
	bytes signature;
};

DecodedVector decoded(size_t _index)
{
	XmssVector const& v = xmssVectors().at(_index);
	return {v.name, fromHex(v.message), fromHex(v.extendedPublicKey), fromHex(v.signature)};
}

bool verify(bytes const& _message, bytes const& _signature, bytes const& _extendedPublicKey)
{
	return xmssVerify(bytesConstRef(&_message), bytesConstRef(&_signature), bytesConstRef(&_extendedPublicKey));
}

bool verify(DecodedVector const& _v)
{
	return verify(_v.message, _v.signature, _v.extendedPublicKey);
}

/// Builds the input of the precompiled contract:
/// uint32 message_length (big-endian) || message || signature || extended_pk.
bytes precompileInput(bytes const& _message, bytes const& _signature, bytes const& _extendedPublicKey)
{
	bytes input{
		static_cast<uint8_t>(_message.size() >> 24),
		static_cast<uint8_t>(_message.size() >> 16),
		static_cast<uint8_t>(_message.size() >> 8),
		static_cast<uint8_t>(_message.size())
	};
	input += _message;
	input += _signature;
	input += _extendedPublicKey;
	return input;
}

bool verifyPrecompileInput(bytes const& _input)
{
	return xmssVerifyPrecompileInput(bytesConstRef(&_input));
}

bytes withFlippedBit(bytes _data, size_t _index)
{
	_data.at(_index) ^= 0x01;
	return _data;
}

bytes withLength(bytes _data, size_t _size)
{
	_data.resize(_size, 0);
	return _data;
}

